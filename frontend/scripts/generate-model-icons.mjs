import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const frontendDirectory = path.resolve(scriptDirectory, '..');
const iconsDirectory = path.join(frontendDirectory, 'node_modules', '@lobehub', 'icons', 'es');
const tocPath = path.join(iconsDirectory, 'toc.json');
const namesOutputPath = path.join(frontendDirectory, 'src', 'features', 'models', 'data', 'model-icon-names.generated.ts');
const loadersOutputPath = path.join(frontendDirectory, 'src', 'features', 'models', 'data', 'model-icon-loaders.generated.ts');
const checkOnly = process.argv.includes('--check');
const prettierOptions = await prettier.resolveConfig(namesOutputPath);

function readIconMetadata() {
  const toc = JSON.parse(fs.readFileSync(tocPath, 'utf8'));
  const allIcons = toc.map(({ id }) => id).sort((left, right) => left.localeCompare(right));
  const selectorIcons = toc
    .filter(({ group }) => group === 'provider' || group === 'model')
    .map(({ id }) => id)
    .sort((left, right) => left.localeCompare(right));

  if (new Set(allIcons).size !== allIcons.length) {
    throw new Error('Duplicate icon IDs found in @lobehub/icons TOC.');
  }

  for (const icon of allIcons) {
    const modulePath = path.join(iconsDirectory, icon, 'components', 'Mono.js');
    if (!fs.existsSync(modulePath)) {
      throw new Error(`Missing Mono icon module for ${icon}: ${modulePath}`);
    }
  }

  return { allIcons, selectorIcons };
}

function renderNamesModule(icons) {
  const names = icons.map((icon) => `  ${JSON.stringify(icon)},`).join('\n');
  return `// This file is generated by scripts/generate-model-icons.mjs. Do not edit manually.\n\nexport const MODEL_ICON_NAMES = [\n${names}\n] as const;\n`;
}

function renderLoadersModule(icons) {
  const loaders = icons
    .map((icon) => `  ${JSON.stringify(icon)}: () => import('@lobehub/icons/es/${icon}/components/Mono.js'),`)
    .join('\n');

  return `// This file is generated by scripts/generate-model-icons.mjs. Do not edit manually.\n\nimport type { ComponentType, SVGProps } from 'react';\n\nexport type ModelIconComponent = ComponentType<SVGProps<SVGSVGElement> & { size?: string | number }>;\nexport type ModelIconModule = { default: ModelIconComponent };\nexport type ModelIconLoader = () => Promise<ModelIconModule>;\n\nexport const MODEL_ICON_LOADERS: Readonly<Record<string, ModelIconLoader>> = {\n${loaders}\n};\n`;
}

async function formatTypeScript(source) {
  return prettier.format(source, {
    ...prettierOptions,
    filepath: namesOutputPath,
  });
}

async function updateGeneratedFile(outputPath, source) {
  const generated = await formatTypeScript(source);
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;

  if (current === generated) {
    return false;
  }

  if (!checkOnly) {
    fs.writeFileSync(outputPath, generated);
  }

  return true;
}

const { allIcons, selectorIcons } = readIconMetadata();
const staleFiles = [];

if (await updateGeneratedFile(namesOutputPath, renderNamesModule(selectorIcons))) {
  staleFiles.push(path.relative(frontendDirectory, namesOutputPath));
}
if (await updateGeneratedFile(loadersOutputPath, renderLoadersModule(allIcons))) {
  staleFiles.push(path.relative(frontendDirectory, loadersOutputPath));
}

if (staleFiles.length === 0) {
  process.stdout.write('Model icon modules are up to date.\n');
  process.exit(0);
}

if (checkOnly) {
  process.stderr.write(`Model icon modules are stale: ${staleFiles.join(', ')}. Run pnpm generate:model-icons.\n`);
  process.exit(1);
}

for (const outputPath of staleFiles) {
  process.stdout.write(`Wrote ${outputPath}.\n`);
}
